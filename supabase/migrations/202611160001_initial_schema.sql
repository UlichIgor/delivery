-- Feast Sushi: initial Supabase schema
-- Run this file once in Supabase SQL Editor.

create table if not exists public.products (
  id bigint primary key,
  title text not null,
  description text not null default '',
  category text not null,
  price numeric(10,2) not null check (price >= 0),
  image text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(id),
  delivery_address text not null,
  notes text not null default '',
  status text not null default 'new' check (status in ('new','confirmed','preparing','delivering','completed','cancelled')),
  total numeric(10,2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  product_title text not null,
  unit_price numeric(10,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(10,2) not null check (line_total >= 0)
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  customer_name text not null default 'Гість',
  rating integer not null check (rating between 1 and 5),
  message text not null check (char_length(message) between 5 and 1200),
  is_approved boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists order_items_order_id_idx on public.order_items(order_id);
create index if not exists reviews_approved_created_idx on public.reviews(is_approved, created_at desc);

alter table public.products enable row level security;
alter table public.customers enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.reviews enable row level security;

drop policy if exists "Anyone can read active products" on public.products;
create policy "Anyone can read active products" on public.products
  for select to anon, authenticated using (is_active = true);

drop policy if exists "Visitors can submit reviews" on public.reviews;
create policy "Visitors can submit reviews" on public.reviews
  for insert to anon, authenticated
  with check (is_approved = false and rating between 1 and 5 and char_length(message) between 5 and 1200);

drop policy if exists "Anyone can read approved reviews" on public.reviews;
create policy "Anyone can read approved reviews" on public.reviews
  for select to anon, authenticated using (is_approved = true);

-- The browser can create an order only through this function. It cannot read customer
-- records or other orders. Prices are always taken from the database, not the browser.
create or replace function public.submit_order(
  p_name text,
  p_phone text,
  p_address text,
  p_notes text,
  p_items jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_customer_id bigint;
  v_order_id bigint;
  v_total numeric(10,2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_quantity integer;
  v_count integer := 0;
begin
  if coalesce(length(trim(p_name)), 0) < 2 then
    raise exception 'Вкажіть ім’я (щонайменше 2 символи)';
  end if;
  if coalesce(length(regexp_replace(p_phone, '[^0-9+]', '', 'g')), 0) < 10 then
    raise exception 'Перевірте номер телефону';
  end if;
  if coalesce(length(trim(p_address)), 0) < 5 then
    raise exception 'Вкажіть адресу доставки';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Кошик порожній';
  end if;

  insert into public.customers(name, phone)
  values (trim(p_name), trim(p_phone))
  on conflict (phone) do update set name = excluded.name, updated_at = now()
  returning id into v_customer_id;

  insert into public.orders(customer_id, delivery_address, notes)
  values (v_customer_id, trim(p_address), coalesce(trim(p_notes), ''))
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := (v_item->>'quantity')::integer;
    if v_quantity < 1 or v_quantity > 50 then
      raise exception 'Некоректна кількість товару';
    end if;

    select * into v_product
    from public.products
    where id = (v_item->>'product_id')::bigint and is_active = true;

    if not found then
      raise exception 'Один із товарів більше недоступний';
    end if;

    insert into public.order_items(order_id, product_id, product_title, unit_price, quantity, line_total)
    values (v_order_id, v_product.id, v_product.title, v_product.price, v_quantity, v_product.price * v_quantity);

    v_total := v_total + v_product.price * v_quantity;
    v_count := v_count + 1;
  end loop;

  if v_count = 0 then
    raise exception 'Кошик порожній';
  end if;

  update public.orders set total = v_total where id = v_order_id;
  return v_order_id;
end;
$$;

revoke all on function public.submit_order(text,text,text,text,jsonb) from public;
grant execute on function public.submit_order(text,text,text,text,jsonb) to anon, authenticated;

